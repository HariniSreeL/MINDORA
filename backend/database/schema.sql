-- Mindora SQLite Database Schema
-- SIH26003 – AI-Assisted Cognitive Gaming and Memory Support Platform

PRAGMA foreign_keys = ON;

-- 1. Users (Loved Ones / Family Members)
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    uuid TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    preferred_language TEXT NOT NULL DEFAULT 'English',
    age INTEGER,
    emergency_contact TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Caregivers (Family members / care partners)
CREATE TABLE IF NOT EXISTS caregivers (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    uuid TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    phone TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Pairing invitations generated by a loved one
CREATE TABLE IF NOT EXISTS pairing_invites (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    pairing_code TEXT UNIQUE NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'used', 'expired')),
    expires_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 4. Caregiver-user pairing (explicit authorization)
CREATE TABLE IF NOT EXISTS caregiver_pairing (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    caregiver_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    pairing_code TEXT,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('pending', 'active', 'rejected', 'revoked')),
    relationship TEXT DEFAULT 'Family Member',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    paired_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (caregiver_id) REFERENCES caregivers(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE(caregiver_id, user_id)
);

-- 5. Game sessions (started, completed, interrupted)
CREATE TABLE IF NOT EXISTS game_sessions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    game_id TEXT NOT NULL,
    game_name TEXT,
    level INTEGER NOT NULL DEFAULT 1,
    duration_seconds REAL NOT NULL DEFAULT 0.0,
    moves INTEGER NOT NULL DEFAULT 0,
    correct_matches INTEGER NOT NULL DEFAULT 0,
    mistakes INTEGER NOT NULL DEFAULT 0,
    hints_used INTEGER NOT NULL DEFAULT 0,
    total_attempts INTEGER NOT NULL DEFAULT 0,
    completed INTEGER NOT NULL DEFAULT 0 CHECK (completed IN (0, 1)),
    status TEXT NOT NULL DEFAULT 'started' CHECK (status IN ('started', 'completed', 'interrupted', 'abandoned')),
    relaxed_mode INTEGER NOT NULL DEFAULT 0 CHECK (relaxed_mode IN (0, 1)),
    cognitive_domain TEXT DEFAULT 'general',
    score REAL DEFAULT 0.0,
    performance_band TEXT DEFAULT 'steady',
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 6. Game results (one row per submitted session)
CREATE TABLE IF NOT EXISTS game_results (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id INTEGER NOT NULL UNIQUE,
    user_id INTEGER NOT NULL,
    game_id TEXT NOT NULL,
    level INTEGER NOT NULL DEFAULT 1,
    score REAL DEFAULT 0.0,
    correct_answers INTEGER NOT NULL DEFAULT 0,
    incorrect_answers INTEGER NOT NULL DEFAULT 0,
    hints_used INTEGER NOT NULL DEFAULT 0,
    duration_seconds REAL NOT NULL DEFAULT 0.0,
    completion_status TEXT NOT NULL DEFAULT 'completed',
    submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (session_id) REFERENCES game_sessions(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 7. Game-wise progress
CREATE TABLE IF NOT EXISTS game_progress (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    game_id TEXT NOT NULL,
    games_played INTEGER NOT NULL DEFAULT 0,
    total_score REAL NOT NULL DEFAULT 0.0,
    best_score REAL NOT NULL DEFAULT 0.0,
    total_duration_seconds REAL NOT NULL DEFAULT 0.0,
    last_played_at TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE(user_id, game_id)
);

-- 8. Level progression
CREATE TABLE IF NOT EXISTS level_progression (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    game_id TEXT NOT NULL,
    unlocked_level INTEGER NOT NULL DEFAULT 1,
    completed_levels TEXT NOT NULL DEFAULT '[]',
    stars_map TEXT NOT NULL DEFAULT '{}',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE(user_id, game_id)
);

-- 9. Mood records
CREATE TABLE IF NOT EXISTS mood_logs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    mood TEXT NOT NULL,
    energy_level INTEGER NOT NULL DEFAULT 3 CHECK (energy_level BETWEEN 1 AND 5),
    note TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 10. Feel Good / activity records
CREATE TABLE IF NOT EXISTS feel_good_activities (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    activity_type TEXT NOT NULL,
    title TEXT,
    duration_seconds REAL NOT NULL DEFAULT 0.0,
    completed INTEGER NOT NULL DEFAULT 1 CHECK (completed IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 11. User preferences (including mood-share consent)
CREATE TABLE IF NOT EXISTS user_preferences (
    user_id INTEGER PRIMARY KEY,
    preferred_language TEXT NOT NULL DEFAULT 'English',
    share_mood_with_caregiver INTEGER NOT NULL DEFAULT 0 CHECK (share_mood_with_caregiver IN (0, 1)),
    text_size TEXT NOT NULL DEFAULT 'Medium',
    background_music INTEGER NOT NULL DEFAULT 1 CHECK (background_music IN (0, 1)),
    music_volume REAL NOT NULL DEFAULT 0.5,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 12. Adaptive difficulty state (rule-based engine)
CREATE TABLE IF NOT EXISTS adaptive_difficulty_states (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    game_id TEXT NOT NULL,
    current_band TEXT NOT NULL DEFAULT 'steady' CHECK (current_band IN ('encourage', 'steady', 'advance')),
    recommended_level INTEGER NOT NULL DEFAULT 1,
    accuracy_ratio REAL DEFAULT 0.0,
    consecutive_successes INTEGER DEFAULT 0,
    consecutive_struggles INTEGER DEFAULT 0,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE(user_id, game_id)
);

-- 13. Revoked JWT tokens (logout / invalidation)
CREATE TABLE IF NOT EXISTS revoked_tokens (
    jti TEXT PRIMARY KEY,
    user_id INTEGER,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_caregivers_email ON caregivers(email);
CREATE INDEX IF NOT EXISTS idx_pairing_caregiver ON caregiver_pairing(caregiver_id);
CREATE INDEX IF NOT EXISTS idx_pairing_user ON caregiver_pairing(user_id);
CREATE INDEX IF NOT EXISTS idx_pairing_invites_code ON pairing_invites(pairing_code);
CREATE INDEX IF NOT EXISTS idx_sessions_user_game ON game_sessions(user_id, game_id, created_at);
CREATE INDEX IF NOT EXISTS idx_results_user ON game_results(user_id, submitted_at);
CREATE INDEX IF NOT EXISTS idx_mood_user_date ON mood_logs(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_feel_good_user ON feel_good_activities(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_revoked_jti ON revoked_tokens(jti);
